# The agent's cursor for the window manager scene: the frames of an XCursor
# (the user's own theme), as a sheet of pictures with a pixel of nothing round
# each, and agent-cursor.plm to draw them: the sheet, its layout, the tip, and
# which frame shows at a time, from the theme's own delays.
#
#   python3 agent-cursor.py CURSOR_FILE SIZE DRAWN OUT
#
# SIZE: the frames read (pixels); DRAWN: how big the cursor is drawn (logical
# pixels). Writes OUT/agent-cursor.rgba (to be made a PNG), its size as
# OUT/agent-cursor.size (WxH), and OUT/agent-cursor.plm.
import struct
import sys

path, size, drawn, out = sys.argv[1], int(sys.argv[2]), float(sys.argv[3]), sys.argv[4]
data = open(path, "rb").read()
count = struct.unpack("<I", data[12:16])[0]
toc = [struct.unpack("<III", data[16 + 12 * i : 28 + 12 * i]) for i in range(count)]
images = [t for t in toc if t[0] == 0xFFFD0002]
sizes = sorted({t[1] for t in images}, key=lambda s: abs(s - size))
images = [t for t in images if t[1] == sizes[0]]

frames = []
for _, _, pos in images:
    w, h, xhot, yhot, delay = struct.unpack("<IIIII", data[pos + 16 : pos + 36])
    frames.append((w, h, xhot, yhot, max(delay, 1), data[pos + 36 : pos + 36 + w * h * 4]))

cell = max(max(f[0], f[1]) for f in frames) + 2
columns = min(len(frames), 24)
rows = (len(frames) + columns - 1) // columns
sheet = bytearray(columns * cell * rows * cell * 4)
for k, (w, h, _, _, _, px) in enumerate(frames):
    ox, oy = (k % columns) * cell + 1, (k // columns) * cell + 1
    for y in range(h):
        for x in range(w):
            b, g, r, a = px[(y * w + x) * 4 : (y * w + x) * 4 + 4]
            # premultiplied BGRA to straight RGBA
            if a:
                r, g, b = (min(255, c * 255 // a) for c in (r, g, b))
            i = ((oy + y) * columns * cell + ox + x) * 4
            sheet[i : i + 4] = bytes((r, g, b, a))
open(f"{out}/agent-cursor.rgba", "wb").write(sheet)
open(f"{out}/agent-cursor.size", "w").write(f"{columns * cell}x{rows * cell}")

# Which frame shows `ms` into the loop: the delays come in runs of the same
# one, so each run is a step through its frames. `agc.clock` is the scene's
# own, in milliseconds.
runs = []
for k, f in enumerate(frames):
    if runs and runs[-1][0] == f[4]:
        runs[-1][2] += 1
    else:
        runs.append([f[4], k, 1])
loop = sum(f[4] for f in frames)
expr, start = "0", loop
for delay, first, n in reversed(runs):
    start -= delay * n
    expr = f"if(agc.ms < {start + delay * n}, {first} + floor((agc.ms - {start}) / {delay}), {expr})"

k = drawn / size
xhot, yhot = frames[0][2], frames[0][3]
open(f"{out}/agent-cursor.plm", "w").write(
    f"""// Generated by agent-cursor.py from the cursor theme: the agent's cursor.
part AgentCursor {{
image agc.sheet = file "agent-cursor.png", {columns * cell * k:.3f}, {rows * cell * k:.3f}
let agc.ms = mod(agc.clock, {loop})
let agc.frame = {expr}
let agc.cols = {columns}
let agc.rows = {rows}
let agc.cell = {cell * k:.3f}
let agc.hx = {(xhot + 1) * k:.3f}
let agc.hy = {(yhot + 1) * k:.3f}
}}
"""
)
